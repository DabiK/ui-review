#!/usr/bin/env node
/**
 * Development installer/remover for the UI Review Native Messaging host.
 *
 * `npm run bridge:install [-- --extension-id <id>]` copies the built bridge bundle into the
 * OS application-data directory, writes a launcher next to it, generates the OS-specific host
 * manifest and registers it for Chrome. Installing outside the repository matters on macOS:
 * Chrome cannot execute files under a TCC-protected folder such as `~/Documents`.
 * `npm run bridge:uninstall` removes the registration and the installed launcher. Windows
 * packaging and standalone binaries are handled separately; on Windows this
 * script writes the manifest and prints the registry command instead of editing the registry.
 */
import { createHash } from 'node:crypto';
import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const distDir = resolve(root, 'dist');
const bridgeDir = join(distDir, 'bridge');
const bundlePath = join(bridgeDir, 'main.cjs');
const manifestTemplatePath = join(
  root,
  'src',
  'bridge',
  'native-messaging-host',
  'manifest.example.json',
);

const APP_DIRECTORY_NAME = 'ui-review';

function fail(message) {
  console.error(`[ui-review] ${message}`);
  process.exit(1);
}

function readOption(args, name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

/** Chrome derives an unpacked extension id from the absolute extension path. */
function computeExtensionId(extensionPath) {
  const hash = createHash('sha256').update(extensionPath).digest().subarray(0, 16);
  const alphabet = 'abcdefghijklmnop';
  return [...hash].map((byte) => alphabet[byte >> 4] + alphabet[byte & 0x0f]).join('');
}

function loadTemplate() {
  return JSON.parse(readFileSync(manifestTemplatePath, 'utf8'));
}

function appDataDirectory(platform) {
  switch (platform) {
    case 'darwin':
      return join(homedir(), 'Library', 'Application Support');
    case 'win32':
      return process.env.APPDATA ?? join(homedir(), 'AppData', 'Roaming');
    default:
      return process.env.XDG_DATA_HOME ?? join(homedir(), '.local', 'share');
  }
}

function installDirectory(platform) {
  return join(appDataDirectory(platform), APP_DIRECTORY_NAME, 'bridge');
}

function writeRunner(platform, origin) {
  const directory = installDirectory(platform);
  const installedBundle = join(directory, 'main.cjs');

  if (platform === 'win32') {
    const runnerPath = join(directory, 'run-bridge.cmd');
    const script = [
      '@echo off',
      'rem Generated by scripts/install-bridge-host.mjs - development launcher for the UI Review bridge.',
      `set UI_REVIEW_BRIDGE_ALLOWED_ORIGINS=${origin}`,
      `"${process.execPath}" "${installedBundle}" %*`,
      '',
    ].join('\r\n');
    writeFileSync(runnerPath, script);
    return runnerPath;
  }

  const runnerPath = join(directory, 'run-bridge.sh');
  const script = [
    '#!/bin/sh',
    '# Generated by scripts/install-bridge-host.mjs - development launcher for the UI Review bridge.',
    `export UI_REVIEW_BRIDGE_ALLOWED_ORIGINS="${origin}"`,
    `exec "${process.execPath}" "${installedBundle}"`,
    '',
  ].join('\n');
  writeFileSync(runnerPath, script, { mode: 0o755 });
  chmodSync(runnerPath, 0o755);
  return runnerPath;
}

function hostManifestDirectory(platform) {
  switch (platform) {
    case 'darwin':
      return join(
        homedir(),
        'Library',
        'Application Support',
        'Google',
        'Chrome',
        'NativeMessagingHosts',
      );
    case 'linux':
      return join(homedir(), '.config', 'google-chrome', 'NativeMessagingHosts');
    default:
      return null;
  }
}

function uninstallFiles(name) {
  const removed = [];

  for (const platform of ['darwin', 'linux']) {
    const directory = hostManifestDirectory(platform);
    if (directory === null) {
      continue;
    }
    const manifestPath = join(directory, `${name}.json`);
    if (existsSync(manifestPath)) {
      rmSync(manifestPath);
      removed.push(manifestPath);
    }
  }

  for (const platform of ['darwin', 'linux', 'win32']) {
    const directory = installDirectory(platform);
    if (existsSync(directory)) {
      // Only the bridge itself is removed; persisted sessions under ui-review/ survive.
      rmSync(directory, { recursive: true, force: true });
      removed.push(directory);
    }
  }

  // Development launchers written next to the build by earlier versions of this script.
  for (const runner of ['run-bridge.sh', 'run-bridge.cmd']) {
    const runnerPath = join(bridgeDir, runner);
    if (existsSync(runnerPath)) {
      rmSync(runnerPath);
      removed.push(runnerPath);
    }
  }

  const localManifest = join(bridgeDir, `${name}.json`);
  if (existsSync(localManifest)) {
    rmSync(localManifest);
    removed.push(localManifest);
  }

  return removed;
}

function install() {
  if (!existsSync(bundlePath)) {
    fail('dist/bridge/main.cjs is missing. Run `npm run build` first.');
  }

  const extensionId = readOption(process.argv.slice(3), '--extension-id') ?? computeExtensionId(distDir);
  if (!/^[a-p]{32}$/.test(extensionId)) {
    fail(`"${extensionId}" is not a Chrome extension id (expected 32 letters a-p).`);
  }

  const template = loadTemplate();
  const origin = `chrome-extension://${extensionId}/`;
  const directory = installDirectory(process.platform);
  mkdirSync(directory, { recursive: true });
  copyFileSync(bundlePath, join(directory, 'main.cjs'));
  if (existsSync(`${bundlePath}.map`)) {
    copyFileSync(`${bundlePath}.map`, join(directory, 'main.cjs.map'));
  }
  const runnerPath = writeRunner(process.platform, origin);
  const hostManifest = { ...template, path: runnerPath, allowed_origins: [origin] };
  const manifestDir = hostManifestDirectory(process.platform);

  if (manifestDir === null) {
    const localManifest = join(bridgeDir, `${template.name}.json`);
    mkdirSync(bridgeDir, { recursive: true });
    writeFileSync(localManifest, `${JSON.stringify(hostManifest, null, 2)}\n`);
    console.log(`[ui-review] Windows: host manifest written to ${localManifest}`);
    console.log(
      `[ui-review] Register it with:\n  reg add "HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\${template.name}" /ve /t REG_SZ /d "${localManifest}" /f`,
    );
  } else {
    mkdirSync(manifestDir, { recursive: true });
    const manifestPath = join(manifestDir, `${template.name}.json`);
    writeFileSync(manifestPath, `${JSON.stringify(hostManifest, null, 2)}\n`);
    console.log(`[ui-review] Host manifest installed: ${manifestPath}`);
  }

  console.log(`[ui-review] Extension id: ${extensionId}`);
  console.log(`[ui-review] Allowed origin: ${origin}`);
  console.log(`[ui-review] Bridge installed: ${directory}`);
  console.log(`[ui-review] Launcher: ${runnerPath}`);
  console.log('[ui-review] Remove it with: npm run bridge:uninstall');
}

function uninstall() {
  const template = loadTemplate();
  const removed = uninstallFiles(template.name);

  if (removed.length === 0) {
    console.log('[ui-review] Nothing to remove.');
  } else {
    for (const path of removed) {
      console.log(`[ui-review] Removed ${path}`);
    }
  }

  if (process.platform === 'win32') {
    console.log(
      `[ui-review] If you registered the Windows host, remove it with:\n  reg delete "HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\${template.name}" /f`,
    );
  }
}

const command = process.argv[2];
if (command === 'install') {
  install();
} else if (command === 'uninstall') {
  uninstall();
} else {
  fail('Usage: node scripts/install-bridge-host.mjs <install|uninstall> [--extension-id <id>]');
}
